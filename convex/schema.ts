import { defineSchema, defineTable } from "convex/server";
import { authTables } from "@convex-dev/auth/server";
import { v } from "convex/values";

export default defineSchema({
  ...authTables,
  accounts: defineTable({
    userId: v.optional(v.id("users")),
    ownerAccountId: v.optional(v.id("accounts")),
    moveType: v.optional(v.string()),
    email: v.string(),
    name: v.string(),
    initials: v.string(),
    role: v.string(),
    planName: v.string(),
    countryFrom: v.string(),
    countryTo: v.string(),
    university: v.string(),
    course: v.string(),
    setupComplete: v.optional(v.boolean()),
    aiConsentAt: v.optional(v.number()),
    aiLastRequestAt: v.optional(v.number()),
    aiRequestDay: v.optional(v.string()),
    aiDailyRequests: v.optional(v.number()),
    paymentStatus: v.union(
      v.literal("not_started"),
      v.literal("prepared"),
      v.literal("approved"),
      v.literal("processing"),
      v.literal("completed"),
      v.literal("failed"),
    ),
    selectedRoute: v.string(),
    sponsorRequestSent: v.boolean(),
  })
    .index("by_email", ["email"])
    .index("by_user", ["userId"]),
  costs: defineTable({
    accountId: v.id("accounts"),
    key: v.string(),
    name: v.string(),
    category: v.string(),
    amount: v.number(),
    due: v.string(),
    paid: v.optional(v.boolean()),
  }).index("by_account", ["accountId"]),
  funding: defineTable({
    accountId: v.id("accounts"),
    key: v.string(),
    name: v.string(),
    type: v.string(),
    amount: v.number(),
    status: v.string(),
    available: v.string(),
  }).index("by_account", ["accountId"]),
  sponsorInvites: defineTable({
    accountId: v.id("accounts"),
    code: v.string(),
    expiresAt: v.number(),
    usedAt: v.optional(v.number()),
  })
    .index("by_code", ["code"])
    .index("by_account", ["accountId"]),
  sponsors: defineTable({
    sponsorAccountId: v.optional(v.id("accounts")),
    accountId: v.id("accounts"),
    key: v.string(),
    name: v.string(),
    relationship: v.string(),
    commitment: v.number(),
    nextDate: v.string(),
    permissions: v.array(v.string()),
  })
    .index("by_account", ["accountId"])
    .index("by_sponsor", ["sponsorAccountId"]),
  wallets: defineTable({
    accountId: v.id("accounts"),
    currency: v.string(),
    symbol: v.string(),
    amount: v.number(),
    gbpValue: v.number(),
    label: v.string(),
  }).index("by_account", ["accountId"]),
  paymentRoutes: defineTable({
    sourceCurrency: v.optional(v.string()),
    targetCurrency: v.optional(v.string()),
    accountId: v.id("accounts"),
    key: v.string(),
    provider: v.string(),
    sourceAmount: v.number(),
    fee: v.number(),
    fxRate: v.number(),
    delivery: v.string(),
    maxBusinessDays: v.optional(v.number()),
    quotedAt: v.optional(v.number()),
    quoteExpiresAt: v.optional(v.number()),
    recommended: v.optional(v.boolean()),
  }).index("by_account", ["accountId"]),
  paymentProposals: defineTable({
    accountId: v.id("accounts"),
    recipient: v.string(),
    recipientLast4: v.string(),
    routeKey: v.string(),
    provider: v.string(),
    fxRate: v.number(),
    sourceCurrency: v.string(),
    targetCurrency: v.string(),
    amountMinor: v.number(),
    sourceMinor: v.number(),
    feeMinor: v.number(),
    totalMinor: v.number(),
    protectedReserveMinor: v.optional(v.number()),
    remainingGBPMinor: v.optional(v.number()),
    delivery: v.string(),
    deadline: v.optional(v.string()),
    bufferBusinessDays: v.optional(v.number()),
    maxBusinessDays: v.optional(v.number()),
    status: v.union(
      v.literal("prepared"),
      v.literal("approved"),
      v.literal("completed"),
      v.literal("cancelled"),
    ),
    createdAt: v.number(),
    expiresAt: v.number(),
    approvedAt: v.optional(v.number()),
    approvedBy: v.optional(v.id("users")),
    completedAt: v.optional(v.number()),
    reference: v.optional(v.string()),
  }).index("by_account", ["accountId"]),
  ledgerEntries: defineTable({
    accountId: v.id("accounts"),
    proposalId: v.id("paymentProposals"),
    reference: v.string(),
    currency: v.string(),
    debitMinor: v.number(),
    beforeMinor: v.number(),
    afterMinor: v.number(),
    recipient: v.string(),
    receivedMinor: v.number(),
    receivedCurrency: v.string(),
    timestamp: v.number(),
  }).index("by_account", ["accountId"]),
  toolExecutions: defineTable({
    accountId: v.id("accounts"),
    name: v.string(),
    arguments: v.any(),
    result: v.any(),
    timestamp: v.number(),
  }).index("by_account", ["accountId"]),
  auditEvents: defineTable({
    accountId: v.id("accounts"),
    type: v.string(),
    detail: v.string(),
    timestamp: v.number(),
    actor: v.string(),
  }).index("by_account", ["accountId"]),
  messages: defineTable({
    toolResults: v.optional(
      v.array(v.object({ name: v.string(), result: v.any() })),
    ),
    chatId: v.optional(v.string()),
    accountId: v.id("accounts"),
    from: v.union(v.literal("agent"), v.literal("user")),
    text: v.string(),
    timestamp: v.number(),
  })
    .index("by_account", ["accountId"])
    .index("by_chat", ["accountId", "chatId"]),
  notifications: defineTable({
    accountId: v.id("accounts"),
    title: v.string(),
    detail: v.string(),
    read: v.boolean(),
    timestamp: v.number(),
  }).index("by_account", ["accountId"]),
  checklist: defineTable({
    accountId: v.id("accounts"),
    key: v.string(),
    label: v.string(),
    detail: v.string(),
    done: v.boolean(),
    position: v.number(),
  }).index("by_account", ["accountId"]),
  appConfig: defineTable({
    accountId: v.id("accounts"),
    key: v.string(),
    value: v.any(),
  }).index("by_account", ["accountId"]),
  sponsorRequests: defineTable({
    accountId: v.id("accounts"),
    sponsorKey: v.string(),
    amount: v.number(),
    purpose: v.string(),
    neededBy: v.string(),
    status: v.union(v.literal("sent"), v.literal("fulfilled")),
    createdAt: v.number(),
  }).index("by_account", ["accountId"]),
  rateAlerts: defineTable({
    accountId: v.id("accounts"),
    pair: v.string(),
    targetRate: v.number(),
    active: v.boolean(),
    createdAt: v.number(),
  }).index("by_account", ["accountId"]),
});
